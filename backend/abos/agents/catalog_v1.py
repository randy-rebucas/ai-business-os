def _task(key: str, title: str, description: str, trigger: dict, *, inputs: list[str], actions: list[str],
          output: str, criteria: list[str], permissions: list[str], priority: str = "normal",
          sla_minutes: int | None = None, approval: str | None = None, depends_on: list[str] | None = None,
          on_failure: str = "escalate") -> dict[str, Any]:
    return {"key": key, "title": title, "description": description, "trigger": trigger, "inputs": inputs,
            "actions": actions, "expected_output": output, "completion_criteria": criteria,
            "required_permissions": permissions, "priority": priority, "sla_minutes": sla_minutes,
            "approval_required": approval is not None, "approval_reason": approval, "depends_on": depends_on or [],
            "policy_refs": [], "failure": {"max_retries": 2, "retry_backoff_minutes": 15, "on_failure": on_failure}}


